export function getVendorHal(vendorKey: string, arch: string): string[] {
  const vk = (vendorKey || '').toLowerCase();
  const a = (arch || '').toLowerCase();

  const hals: string[] = [];

  if (a === 'arm' || a === 'arm64') {
    hals.push('cmsis');
  }

  switch (vk) {
    case 'nordic':
      hals.push('hal_nordic');
      break;
    case 'st':
      hals.push('hal_stm32');
      break;
    case 'espressif':
      hals.push('hal_espressif');
      break;
    case 'raspberrypi':
      hals.push('hal_rpi_pico');
      break;
    case 'nxp':
      hals.push('hal_nxp');
      break;
    case 'ti':
      hals.push('hal_ti');
      break;
    case 'silabs':
      hals.push('hal_silabs');
      break;
    case 'infineon':
      hals.push('hal_infineon');
      break;
    case 'atmel':
    case 'microchip':
      hals.push('hal_atmel');
      break;
    case 'renesas':
      hals.push('hal_renesas');
      break;
    case 'ambiq':
      hals.push('hal_ambiq');
      break;
    case 'gigadevice':
      hals.push('hal_gigadevice');
      break;
    case 'telink':
      hals.push('hal_telink');
      break;
    case 'posix':
    case 'native':
      // Host simulator doesn't need external HAL repositories
      break;
    default:
      if (a === 'xtensa') {
        hals.push('hal_espressif');
      }
      break;
  }

  return hals;
}

export function generateWestManifest(config: ProjectConfig, modules: Module[], board?: Board): string {
  const allowlistSet = new Set<string>();

  // Add board HALs
  if (board) {
    const hals = getVendorHal(board.vendorKey, board.arch);
    for (const h of hals) {
      allowlistSet.add(h);
    }
  } else {
    allowlistSet.add('cmsis');
  }

  // Add required West modules from selected modules
  for (const m of modules) {
    if (m.westModules) {
      for (const wm of m.westModules) {
        allowlistSet.add(wm);
      }
    }
  }

  const sortedAllowlist = Array.from(allowlistSet).sort();

  let allowlistYaml = '';
  for (const item of sortedAllowlist) {
    allowlistYaml += `          - ${item}\n`;
  }

  return `# West manifest for ${config.name}
# Generated by Zephyr Initializer (https://github.com/zephyrproject-rtos)
# NOTE: Only strictly required HAL and modules are allowlisted to minimize download size.

manifest:
  remotes:
    - name: zephyrproject-rtos
      url-base: https://github.com/zephyrproject-rtos

  projects:
    - name: zephyr
      remote: zephyrproject-rtos
      revision: ${config.zephyrVersion || 'main'}
      import:
        name-allowlist:
${allowlistYaml}
  self:
    path: app
`;
}

